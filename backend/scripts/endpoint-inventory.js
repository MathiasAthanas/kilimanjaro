const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const servicesDir = path.join(root, 'services');
const outputFile = path.join(root, 'ENDPOINT_INVENTORY.md');
const httpDecorators = ['Get', 'Post', 'Put', 'Patch', 'Delete', 'All'];

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    return fullPath;
  });
}

function extractDecoratorArg(source, decorator, index = 0) {
  const pattern = new RegExp(`@${decorator}\\s*\\(([^)]*)\\)`, 'g');
  const matches = [...source.matchAll(pattern)];
  const raw = matches[index]?.[1]?.trim();
  if (!raw) return '';
  const stringMatch = raw.match(/['"`]([^'"`]+)['"`]/);
  if (stringMatch) return stringMatch[1];
  const arrayMatch = raw.match(/\[([^\]]+)\]/);
  if (arrayMatch) return arrayMatch[1].replace(/\s+/g, ' ').trim();
  return raw;
}

function normalizePath(prefix, route) {
  const full = `/${[prefix, route].filter(Boolean).join('/')}`;
  return full.replace(/\/+/g, '/').replace(/\/\*$/, '/*');
}

function extractRoutes(filePath) {
  const source = fs.readFileSync(filePath, 'utf8');
  const controllerPrefix = extractDecoratorArg(source, 'Controller');
  const routes = [];
  const methodRegex = /@(Get|Post|Put|Patch|Delete|All)\s*\(([^)]*)\)\s*(?:\r?\n\s*@[^\r\n]+)*\s*(?:async\s+)?([A-Za-z0-9_]+)\s*\(/g;
  let match;

  while ((match = methodRegex.exec(source)) !== null) {
    const [, decorator, rawArg, handler] = match;
    const routeArg = rawArg.trim();
    const paths = routeArg.startsWith('[')
      ? [...routeArg.matchAll(/['"`]([^'"`]+)['"`]/g)].map((item) => item[1])
      : [routeArg.match(/['"`]([^'"`]+)['"`]/)?.[1] || ''];

    for (const routePath of paths) {
      routes.push({
        method: decorator === 'All' ? 'ALL' : decorator.toUpperCase(),
        path: normalizePath(controllerPrefix, routePath),
        handler,
        file: path.relative(root, filePath).replace(/\\/g, '/'),
      });
    }
  }

  if (source.includes('@Controller') && routes.length === 0) {
    const hasHttpDecorator = httpDecorators.some((decorator) => source.includes(`@${decorator}(`));
    if (hasHttpDecorator) {
      throw new Error(`Could not parse routes from ${filePath}`);
    }
  }

  return routes;
}

function main() {
  const services = fs
    .readdirSync(servicesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const lines = [
    '# Backend Endpoint Inventory',
    '',
    `Generated: ${new Date().toISOString()}`,
    '',
    'This file is generated by `npm run test:endpoints:inventory`. It is a route inventory, not a substitute for live E2E tests.',
    '',
  ];
  let total = 0;

  for (const service of services) {
    const srcDir = path.join(servicesDir, service, 'src');
    if (!fs.existsSync(srcDir)) continue;

    const routes = walk(srcDir)
      .filter((file) => file.endsWith('.controller.ts'))
      .flatMap(extractRoutes)
      .sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));

    total += routes.length;
    lines.push(`## ${service}`, '');
    lines.push(`Routes found: ${routes.length}`, '');
    lines.push('| Method | Path | Handler | Source |');
    lines.push('| --- | --- | --- | --- |');
    for (const route of routes) {
      lines.push(`| ${route.method} | \`${route.path}\` | \`${route.handler}\` | \`${route.file}\` |`);
    }
    lines.push('');
  }

  lines.splice(4, 0, `Total routes found: ${total}`, '');
  fs.writeFileSync(outputFile, `${lines.join('\n')}\n`);
  console.log(`Endpoint inventory generated: ${path.relative(process.cwd(), outputFile)}`);
  console.log(`Total routes found: ${total}`);
}

main();
